"""
LLM-as-Judge — Phase 4
Uses Groq to evaluate reply quality on 4 dimensions.
Includes human-judge agreement measurement.
"""
import sys
import json
import time
from pathlib import Path
from typing import Optional

from loguru import logger

sys.path.insert(0, str(Path(__file__).parent.parent.parent))
from src.config import settings


JUDGE_SYSTEM_PROMPT = """You are an expert evaluator of customer support replies for Twitter.

You will be given:
- A customer's tweet (the question/complaint)
- A draft reply generated by an AI agent

Score the reply on EXACTLY THESE 4 dimensions (each 1-5):

1. RELEVANCE (1-5): Does the reply directly address what the customer asked?
   1 = Completely irrelevant | 3 = Partially addresses | 5 = Perfectly on-point

2. GROUNDEDNESS (1-5): Is the reply factually appropriate and avoids hallucination?
   1 = Contains false claims | 3 = Mostly safe | 5 = Completely accurate/appropriate

3. TONE (1-5): Is the tone professional, empathetic, and appropriate for customer support?
   1 = Rude/dismissive | 3 = Neutral | 5 = Perfectly empathetic and professional

4. RESOLUTION (1-5): Does the reply provide a useful next step or solution?
   1 = No actionable content | 3 = Vague next step | 5 = Clear, actionable solution

Output ONLY valid JSON in this exact format (no explanation):
{"relevance": X, "groundedness": X, "tone": X, "resolution": X, "overall": X}

Where "overall" is your holistic 1-5 score (not just the average)."""

JUDGE_USER_PROMPT = """Customer message: {customer_message}

AI draft reply: {draft_reply}

Score this reply (return JSON only):"""


class LLMJudge:
    """
    LLM-as-judge for reply quality evaluation.
    Uses Groq with structured output.
    """

    def __init__(self):
        self._client = None

    def _get_client(self):
        if self._client is None:
            from groq import Groq
            self._client = Groq(api_key=settings.groq_api_key)
        return self._client

    def score(
        self,
        customer_message: str,
        draft_reply: str,
        retries: int = 2,
    ) -> dict:
        """
        Score a single reply.

        Returns:
            {relevance, groundedness, tone, resolution, overall, error}
        """
        client = self._get_client()

        for attempt in range(retries + 1):
            try:
                response = client.chat.completions.create(
                    model=settings.groq_model,
                    messages=[
                        {"role": "system", "content": JUDGE_SYSTEM_PROMPT},
                        {
                            "role": "user",
                            "content": JUDGE_USER_PROMPT.format(
                                customer_message=customer_message[:500],
                                draft_reply=draft_reply[:400],
                            ),
                        },
                    ],
                    max_tokens=80,
                    temperature=0.0,
                )

                raw = response.choices[0].message.content.strip()

                # Extract JSON from response
                import re
                json_match = re.search(r'\{[^}]+\}', raw)
                if json_match:
                    scores = json.loads(json_match.group())
                    # Validate scores
                    for dim in ["relevance", "groundedness", "tone", "resolution", "overall"]:
                        if dim not in scores:
                            scores[dim] = 3
                        scores[dim] = max(1, min(5, int(scores[dim])))
                    scores["error"] = None
                    return scores
                else:
                    raise ValueError(f"No JSON found in: {raw}")

            except Exception as e:
                if attempt < retries:
                    time.sleep(2 ** attempt)
                else:
                    logger.error(f"Judge scoring failed: {e}")
                    return {
                        "relevance": 0,
                        "groundedness": 0,
                        "tone": 0,
                        "resolution": 0,
                        "overall": 0,
                        "error": str(e),
                    }

    def score_batch(
        self,
        examples: list[dict],
        rate_limit_delay: float = 1.0,
    ) -> list[dict]:
        """
        Score a batch of examples.

        Args:
            examples: List of {customer_message, draft_reply}
            rate_limit_delay: Seconds between requests (Groq rate limiting)
        """
        results = []
        for i, ex in enumerate(examples):
            score = self.score(ex["customer_message"], ex["draft_reply"])
            results.append({**ex, **score})

            if i > 0 and i % 5 == 0:
                logger.info(f"Judge progress: {i}/{len(examples)}")
                time.sleep(rate_limit_delay)

        return results

    def compute_aggregate(self, scores: list[dict]) -> dict:
        """Compute aggregate statistics across all scored examples."""
        valid = [s for s in scores if s.get("error") is None]

        if not valid:
            return {"error": "No valid scores"}

        dims = ["relevance", "groundedness", "tone", "resolution", "overall"]
        agg = {}
        for dim in dims:
            vals = [s[dim] for s in valid]
            agg[dim] = {
                "mean": round(sum(vals) / len(vals), 3),
                "min": min(vals),
                "max": max(vals),
                "pct_4_plus": round(sum(1 for v in vals if v >= 4) / len(vals) * 100, 1),
            }

        agg["n_scored"] = len(valid)
        agg["n_failed"] = len(scores) - len(valid)
        return agg


# Global instance
judge = LLMJudge()
